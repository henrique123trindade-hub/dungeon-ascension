export function isBossFloor(floor: number): boolean {
  return floor >= 10 && floor % 10 === 0;
}

export function isMegaBossFloor(floor: number): boolean {
  return floor >= 50 && floor % 50 === 0;
}

export function getBossForFloor(floor: number): BossDef | null {
  if (!isBossFloor(floor)) return null;
  const idx = (Math.floor(floor / 10) - 1) % BOSSES.length;
  const base = BOSSES[idx];
  const cycle = Math.floor((floor - 1) / 100);
  if (cycle === 0) return base;
  return {
    ...base,
    name: `${base.name} Ascendido`,
    title: `${base.title} · Ciclo ${cycle + 1}`,
    isMegaBoss: isMegaBossFloor(floor),
    hpMultiplier: base.hpMultiplier * (1 + cycle * 0.45),
    damageMultiplier: base.damageMultiplier * (1 + cycle * 0.25),
  };
}
