export function getBiomeForFloor(floor: number): BiomeDef {
  const safeFloor = Math.max(1, Math.floor(floor));
  const cycleIndex = Math.floor((safeFloor - 1) / 10) % BIOMES.length;
  return BIOMES[cycleIndex];
}

export function getInfiniteModifierForFloor(floor: number) {
  if (floor <= 100) return null;
  const cycle = Math.floor((floor - 101) / 5);
  const base = INFINITE_FLOOR_MODIFIERS[cycle % INFINITE_FLOOR_MODIFIERS.length];
  const tier = Math.floor((floor - 1) / 100);
  return {
    ...base,
    name: `${base.name} ${'I'.repeat(Math.min(5, tier + 1))}`,
  };
}
